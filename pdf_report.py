"""
pdf_report.py — builds a one-page PDF summary for a single prediction.
"""

from fpdf import FPDF


def build_prediction_pdf(pred: dict) -> bytes:
    pdf = FPDF()
    pdf.add_page()

    # Header
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(15, 26, 61)  # navy-deep
    pdf.cell(0, 12, "Credit Card Approval - Prediction Report", ln=True)

    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(90, 90, 90)
    pdf.cell(0, 8, f"Generated: {pred['timestamp']}", ln=True)
    pdf.ln(4)

    # Result banner
    is_approved = pred["result"] == "Approved"
    if is_approved:
        pdf.set_fill_color(222, 234, 228)  # sage-soft
        pdf.set_text_color(76, 122, 103)
    else:
        pdf.set_fill_color(245, 226, 225)  # coral-soft
        pdf.set_text_color(194, 75, 75)

    pdf.set_font("Helvetica", "B", 16)
    label = "APPROVED" if is_approved else "REJECTED"
    pdf.cell(0, 14, f"  {label}", ln=True, fill=True)
    pdf.ln(4)

    pdf.set_text_color(20, 20, 20)
    pdf.set_font("Helvetica", "", 12)
    # risk_level is stored like "🟢 Low Risk" — strip the emoji, core fonts can't render it
    risk_text = pred["risk_level"].split(" ", 1)[-1] if " " in pred["risk_level"] else pred["risk_level"]

    pdf.cell(0, 8, f"Confidence Score: {pred['confidence']}%", ln=True)
    pdf.cell(0, 8, f"Risk Level: {risk_text}", ln=True)
    pdf.ln(6)

    # Application summary
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(15, 26, 61)
    pdf.cell(0, 10, "Application Summary", ln=True)

    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(40, 40, 40)
    rows = [
        ("Age", f"{pred['age']} years"),
        ("Annual Income", f"Rs. {pred['income']:,.0f}"),
        ("Employment", f"{pred['employment_years']} years"),
        ("Credit History", f"{pred['credit_history_months']} months"),
    ]
    for label, value in rows:
        pdf.set_font("Helvetica", "B", 11)
        pdf.cell(50, 8, label)
        pdf.set_font("Helvetica", "", 11)
        pdf.cell(0, 8, value, ln=True)

    pdf.ln(8)
    pdf.set_font("Helvetica", "I", 9)
    pdf.set_text_color(120, 120, 120)
    pdf.multi_cell(0, 6, "Model: Random Forest + SMOTE | This report is generated by an automated ML model and is for informational purposes only.")

    return bytes(pdf.output())